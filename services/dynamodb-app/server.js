import express from 'express';
import cors from 'cors';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import https from 'node:https';
import fs from 'node:fs';
import {
  DynamoDBClient,
  ListTablesCommand,
  DescribeTableCommand,
  CreateTableCommand,
  DeleteTableCommand
} from '@aws-sdk/client-dynamodb';
import {
  DynamoDBDocumentClient,
  ScanCommand,
  PutCommand,
  DeleteCommand
} from '@aws-sdk/lib-dynamodb';
import { NodeHttpHandler } from '@smithy/node-http-handler';

// Disable TLS strict verification for local emulator self-signed certificates
process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;

app.use(cors());
app.use(express.json());

const agent = new https.Agent({
  rejectUnauthorized: false
});

// Dynamically read emulator credentials generated by aws-emulator
function getEmulatorCredentials() {
  const baseDir = process.env.AWS_EMULATOR_DATA_DIR || '/home/emulator/.aws/emulator';
  try {
    if (fs.existsSync(baseDir)) {
      const portDirs = fs.readdirSync(baseDir).filter((f) => /^\d+$/.test(f));
      if (portDirs.length > 0) {
        const credPath = path.join(baseDir, portDirs[0], 'emulator_credentials');
        if (fs.existsSync(credPath)) {
          const content = fs.readFileSync(credPath, 'utf8');
          const accessKeyMatch = content.match(/aws_access_key_id\s*=\s*([^\r\n]+)/);
          const secretKeyMatch = content.match(/aws_secret_access_key\s*=\s*([^\r\n]+)/);
          if (accessKeyMatch && secretKeyMatch) {
            return {
              accessKeyId: accessKeyMatch[1].trim(),
              secretAccessKey: secretKeyMatch[1].trim()
            };
          }
        }
      }
    }
  } catch (err) {
    console.warn('Could not read emulator credentials from volume:', err.message);
  }

  return {
    accessKeyId: process.env.AWS_ACCESS_KEY_ID || 'test',
    secretAccessKey: process.env.AWS_SECRET_ACCESS_KEY || 'test'
  };
}

function getClients() {
  const credentials = getEmulatorCredentials();
  const ddbClient = new DynamoDBClient({
    endpoint: process.env.AWS_ENDPOINT_URL || 'https://aws-emulator:9297',
    region: process.env.AWS_DEFAULT_REGION || 'us-east-1',
    credentials,
    requestHandler: new NodeHttpHandler({
      httpsAgent: agent
    })
  });

  const docClient = DynamoDBDocumentClient.from(ddbClient, {
    marshallOptions: { removeUndefinedValues: true }
  });

  return { ddbClient, docClient };
}

// Health check endpoint
app.get('/api/health', async (req, res) => {
  try {
    const { ddbClient } = getClients();
    const data = await ddbClient.send(new ListTablesCommand({ Limit: 10 }));
    res.json({
      status: 'connected',
      endpoint: process.env.AWS_ENDPOINT_URL || 'https://aws-emulator:9297',
      region: process.env.AWS_DEFAULT_REGION || 'us-east-1',
      tablesCount: data.TableNames?.length || 0
    });
  } catch (error) {
    res.status(503).json({
      status: 'disconnected',
      endpoint: process.env.AWS_ENDPOINT_URL || 'https://aws-emulator:9297',
      region: process.env.AWS_DEFAULT_REGION || 'us-east-1',
      error: error.message
    });
  }
});

// List all tables
app.get('/api/tables', async (req, res) => {
  try {
    const { ddbClient } = getClients();
    const listRes = await ddbClient.send(new ListTablesCommand({}));
    const tableNames = listRes.TableNames || [];

    const tables = await Promise.all(
      tableNames.map(async (name) => {
        try {
          const desc = await ddbClient.send(new DescribeTableCommand({ TableName: name }));
          return desc.Table;
        } catch {
          return { TableName: name, TableStatus: 'UNKNOWN' };
        }
      })
    );

    res.json({ tables });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

// Create a new table
app.post('/api/tables', async (req, res) => {
  try {
    const { ddbClient } = getClients();
    const { tableName, partitionKey, sortKey, billingMode = 'PAY_PER_REQUEST' } = req.body;

    if (!tableName || !partitionKey?.name) {
      return res.status(400).json({ error: 'Table name and partition key name are required.' });
    }

    const attributeDefinitions = [
      { AttributeName: partitionKey.name, AttributeType: partitionKey.type || 'S' }
    ];

    const keySchema = [
      { AttributeName: partitionKey.name, KeyType: 'HASH' }
    ];

    if (sortKey?.name) {
      attributeDefinitions.push({
        AttributeName: sortKey.name,
        AttributeType: sortKey.type || 'S'
      });
      keySchema.push({
        AttributeName: sortKey.name,
        KeyType: 'RANGE'
      });
    }

    const command = new CreateTableCommand({
      TableName: tableName,
      AttributeDefinitions: attributeDefinitions,
      KeySchema: keySchema,
      BillingMode: billingMode
    });

    const result = await ddbClient.send(command);
    res.status(201).json({ table: result.TableDescription });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

// Delete table
app.delete('/api/tables/:tableName', async (req, res) => {
  try {
    const { ddbClient } = getClients();
    const { tableName } = req.params;
    await ddbClient.send(new DeleteTableCommand({ TableName: tableName }));
    res.json({ message: `Table "${tableName}" deleted successfully` });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

// Scan items from table
app.get('/api/tables/:tableName/items', async (req, res) => {
  try {
    const { docClient } = getClients();
    const { tableName } = req.params;
    const scanRes = await docClient.send(new ScanCommand({ TableName: tableName, Limit: 100 }));
    res.json({
      items: scanRes.Items || [],
      count: scanRes.Count || 0,
      scannedCount: scanRes.ScannedCount || 0
    });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

// Put / Insert item
app.post('/api/tables/:tableName/items', async (req, res) => {
  try {
    const { docClient } = getClients();
    const { tableName } = req.params;
    const { item } = req.body;

    if (!item || typeof item !== 'object') {
      return res.status(400).json({ error: 'A valid item object is required' });
    }

    await docClient.send(new PutCommand({ TableName: tableName, Item: item }));
    res.status(201).json({ message: 'Item created successfully', item });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

// Delete item
app.delete('/api/tables/:tableName/items', async (req, res) => {
  try {
    const { docClient } = getClients();
    const { tableName } = req.params;
    const { key } = req.body;

    if (!key || typeof key !== 'object') {
      return res.status(400).json({ error: 'Primary key is required for deletion' });
    }

    await docClient.send(new DeleteCommand({ TableName: tableName, Key: key }));
    res.json({ message: 'Item deleted successfully' });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

// Seed sample table and items
app.post('/api/seed', async (req, res) => {
  const sampleTable = 'Products';
  try {
    const { ddbClient, docClient } = getClients();
    const listRes = await ddbClient.send(new ListTablesCommand({}));
    if (!listRes.TableNames?.includes(sampleTable)) {
      await ddbClient.send(
        new CreateTableCommand({
          TableName: sampleTable,
          AttributeDefinitions: [
            { AttributeName: 'id', AttributeType: 'S' },
            { AttributeName: 'category', AttributeType: 'S' }
          ],
          KeySchema: [
            { AttributeName: 'id', KeyType: 'HASH' },
            { AttributeName: 'category', KeyType: 'RANGE' }
          ],
          BillingMode: 'PAY_PER_REQUEST'
        })
      );
      // Brief pause to allow the table to transition to ACTIVE status
      await new Promise((resolve) => setTimeout(resolve, 1000));
    }

    const sampleItems = [
      { id: 'prod-001', category: 'Electronics', name: 'Wireless Headphones', price: 199.99, stock: 45, inStock: true },
      { id: 'prod-002', category: 'Electronics', name: 'Mechanical Keyboard', price: 89.50, stock: 120, inStock: true },
      { id: 'prod-003', category: 'Books', name: 'Designing Data-Intensive Applications', price: 42.00, stock: 75, inStock: true },
      { id: 'prod-004', category: 'Home', name: 'Smart Aroma Diffuser', price: 34.99, stock: 15, inStock: true },
      { id: 'prod-005', category: 'Fitness', name: 'Stainless Steel Water Bottle (1L)', price: 24.50, stock: 200, inStock: true }
    ];

    for (const item of sampleItems) {
      await docClient.send(new PutCommand({ TableName: sampleTable, Item: item }));
    }

    res.json({ message: 'Sample "Products" table created with 5 items!' });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

// Serve frontend in production
const distPath = path.join(__dirname, 'dist');
app.use(express.static(distPath));

app.get('*', (req, res) => {
  res.sendFile(path.join(distPath, 'index.html'));
});

app.listen(PORT, '0.0.0.0', () => {
  console.log(`DynamoDB Web App listening on http://0.0.0.0:${PORT}`);
  console.log(`Connecting to AWS Emulator at: ${process.env.AWS_ENDPOINT_URL || 'https://aws-emulator:9297'}`);
});
